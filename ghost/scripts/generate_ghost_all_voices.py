# -*- coding: utf-8 -*-
"""
ghost/scripts/generate_ghost_all_voices.py - GHOST PROTOCOL 全シナリオ音声生成

all_dialogues.json の全セリフを Gemini 3.8 Flash TTS (Vertex AI) で音声化し、
128kbps MP3 として ghost/assets/audio/voice/ に保存する。
生成済みファイルはスキップするため、途中で中断しても再実行で再開できる。
最後にゲーム側が参照する voice-manifest.js を自動生成する。
"""

import argparse
import json
import os
import subprocess
import sys
import tempfile
import time
from pathlib import Path

from dotenv import load_dotenv
from google import genai
from google.genai import types

sys.path.insert(0, str(Path(__file__).resolve().parent))
from ghost_voice_text import VOICE_PROFILES, normalize_for_tts  # noqa: E402

sys.stdout.reconfigure(encoding="utf-8", line_buffering=True)
load_dotenv()

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
GHOST_DIR = REPO_ROOT / "ghost"
DIALOGUES_PATH = Path(__file__).resolve().parent / "all_dialogues.json"
VOICE_DIR = GHOST_DIR / "assets" / "audio" / "voice"
MANIFEST_PATH = GHOST_DIR / "js" / "voice-manifest.js"
REPORT_PATH = Path(__file__).resolve().parent / "voice_generation_report.json"
MODEL_NAME = "gemini-3.8-flash-tts"

project_id = os.environ.get("GOOGLE_CLOUD_PROJECT")
location = os.environ.get("GOOGLE_CLOUD_LOCATION", "global")

if not project_id:
    print("エラー: .env ファイル等で GOOGLE_CLOUD_PROJECT を設定してください。")
    sys.exit(1)

client = genai.Client(vertexai=True, project=project_id, location=location)


def load_dialogues() -> list[dict]:
    if not DIALOGUES_PATH.exists():
        print(f"エラー: {DIALOGUES_PATH} が見つかりません。先に extract_ghost_dialogues.js を実行してください。")
        sys.exit(1)
    return json.loads(DIALOGUES_PATH.read_text(encoding="utf-8"))


def output_path(entry: dict) -> Path:
    return GHOST_DIR / entry["file"]


def is_ready(entry: dict) -> bool:
    path = output_path(entry)
    return path.exists() and path.stat().st_size > 1000


def build_manifest(entries: list[dict]) -> dict[str, str]:
    manifest: dict[str, str] = {}
    for entry in entries:
        if not is_ready(entry):
            continue
        key = f"{entry['speaker']}::{entry['text']}"
        manifest[key] = entry["file"]
    return manifest


def write_manifest(entries: list[dict]) -> int:
    manifest = build_manifest(entries)
    MANIFEST_PATH.parent.mkdir(parents=True, exist_ok=True)
    content = (
        "// Auto-generated by ghost/scripts/generate_ghost_all_voices.py.\n"
        "// 手動編集しないでください。セリフ追加・変更時は再生成してください。\n"
        f"window.GHOST_VOICE_MANIFEST = {json.dumps(manifest, ensure_ascii=False, indent=2)};\n"
    )
    MANIFEST_PATH.write_text(content, encoding="utf-8")
    return len(manifest)


def generate_voice(entry: dict) -> None:
    profile = VOICE_PROFILES.get(entry["speaker"], VOICE_PROFILES["narrator"])
    tts_text = normalize_for_tts(entry["text"])
    target_path = output_path(entry)
    target_path.parent.mkdir(parents=True, exist_ok=True)

    with tempfile.NamedTemporaryFile(suffix=".wav", delete=False, dir=target_path.parent) as temp_wav:
        temp_wav_path = Path(temp_wav.name)

    try:
        response = client.models.generate_content(
            model=MODEL_NAME,
            contents=types.Content(
                role="user",
                parts=[
                    types.Part(
                        text=tts_text,
                        speech_metadata=types.SpeechMetadata(style=profile["style"]),
                    )
                ],
            ),
            config=types.GenerateContentConfig(
                response_modalities=["AUDIO"],
                speech_config=types.SpeechConfig(
                    voice_config=types.VoiceConfig(
                        prebuilt_voice_config=types.PrebuiltVoiceConfig(
                            voice_name=profile["voice"],
                        )
                    )
                ),
            ),
        )

        audio_bytes = response.candidates[0].content.parts[0].inline_data.data
        if not audio_bytes:
            raise ValueError("音声データがレスポンスに含まれていません")
        temp_wav_path.write_bytes(audio_bytes)

        cmd = [
            "ffmpeg",
            "-y",
            "-i",
            str(temp_wav_path),
            "-codec:a",
            "libmp3lame",
            "-b:a",
            "128k",
            str(target_path),
        ]
        subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)

        if not target_path.exists() or target_path.stat().st_size <= 1000:
            raise ValueError("生成されたMP3ファイルが空、または小さすぎます")
    finally:
        if temp_wav_path.exists():
            temp_wav_path.unlink()


def select_entries(entries: list[dict], args: argparse.Namespace) -> list[dict]:
    selected = entries
    if args.id:
        ids = {value.strip() for value in args.id.split(",") if value.strip()}
        selected = [entry for entry in selected if entry["id"] in ids]
    if args.speaker:
        selected = [entry for entry in selected if entry["speaker"] == args.speaker]
    if args.limit:
        selected = selected[: args.limit]
    return selected


def run_generation(entries: list[dict], args: argparse.Namespace) -> tuple[int, int, int, list[dict]]:
    success = 0
    skipped = 0
    failed = 0
    failures: list[dict] = []

    for index, entry in enumerate(entries, start=1):
        target_path = output_path(entry)
        if is_ready(entry) and not args.force:
            skipped += 1
            print(f"[{index:03d}/{len(entries)}] SKIP {entry['id']} (生成済み)")
            continue

        profile = VOICE_PROFILES.get(entry["speaker"], VOICE_PROFILES["narrator"])
        print(
            f"[{index:03d}/{len(entries)}] {entry['id']} "
            f"({entry['speaker']} / {profile['voice']}) -> {entry['file']}",
            flush=True,
        )

        last_error: Exception | None = None
        for attempt in range(1, args.retries + 1):
            try:
                generate_voice(entry)
                size_kb = target_path.stat().st_size / 1024
                print(f"  -> OK ({size_kb:.1f} KB)", flush=True)
                success += 1
                write_manifest(entries)
                time.sleep(args.sleep)
                last_error = None
                break
            except Exception as error:  # noqa: BLE001 - API/SDK固有の例外をまとめて再試行する
                last_error = error
                print(f"  -> 試行 {attempt}/{args.retries} 失敗: {error}", flush=True)
                if attempt < args.retries:
                    time.sleep(args.retry_wait * attempt)

        if last_error is not None:
            failed += 1
            failures.append({"id": entry["id"], "error": str(last_error)})
            print(f"  -> 最終失敗: {entry['id']}", flush=True)

    return success, skipped, failed, failures


def main() -> None:
    parser = argparse.ArgumentParser(description="GHOST PROTOCOL 全シナリオ音声生成")
    parser.add_argument("--id", help="カンマ区切りのセリフIDのみ生成")
    parser.add_argument("--speaker", help="指定した話者のみ生成")
    parser.add_argument("--limit", type=int, help="先頭から指定件数のみ生成")
    parser.add_argument("--force", action="store_true", help="生成済みファイルも再生成")
    parser.add_argument("--manifest-only", action="store_true", help="音声生成せずマニフェストのみ再構築")
    parser.add_argument("--sleep", type=float, default=0.35, help="成功時の待機秒数")
    parser.add_argument("--retries", type=int, default=3, help="1セリフあたりの最大試行回数")
    parser.add_argument("--retry-wait", type=float, default=1.5, help="再試行の基本待機秒数")
    args = parser.parse_args()

    entries = load_dialogues()

    if args.manifest_only:
        count = write_manifest(entries)
        print(f"マニフェスト再構築完了: {count} 件 -> {MANIFEST_PATH}")
        return

    selected = select_entries(entries, args)
    if not selected:
        print("対象セリフが見つかりません。")
        sys.exit(1)

    print("==================================================")
    print(f"GHOST PROTOCOL - 全シナリオ音声生成 ({len(selected)} セリフ)")
    print(f"プロジェクト: {project_id} / リージョン: {location}")
    print("==================================================")

    success, skipped, failed, failures = run_generation(selected, args)

    manifest_count = write_manifest(entries)
    REPORT_PATH.write_text(
        json.dumps(
            {
                "generated": success,
                "skipped": skipped,
                "failed": failed,
                "failures": failures,
                "manifest_entries": manifest_count,
            },
            ensure_ascii=False,
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )

    print("\n==================================================")
    print(f"生成完了: 新規 {success} / スキップ {skipped} / 失敗 {failed}")
    print(f"マニフェスト: {manifest_count} 件 -> {MANIFEST_PATH}")
    print(f"レポート: {REPORT_PATH}")
    print("==================================================")

    if failed:
        sys.exit(2)


if __name__ == "__main__":
    main()
